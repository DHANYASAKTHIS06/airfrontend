export function findSupportedLocation(query) {
  if (!query || typeof query !== 'string') return null;
  const clean = query.trim().toLowerCase();
  
  if (SUPPORTED_LOCATIONS[clean]) {
    return SUPPORTED_LOCATIONS[clean];
  }
  
  // Partial match
  const matchKey = Object.keys(SUPPORTED_LOCATIONS).find(k => 
    k === clean || k.startsWith(clean) || SUPPORTED_LOCATIONS[k].name.toLowerCase() === clean
  );
  
  return matchKey ? SUPPORTED_LOCATIONS[matchKey] : null;
}
